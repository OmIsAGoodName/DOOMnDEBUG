import type { AudioManifest } from '@contracts';
import type { ResolvedTimeline } from '../types';
import { computeMouthTrack } from './lipsync';
import { config } from '../../config';

export interface AudioEngineOptions {
  onProgress?: (loaded: number, total: number) => void;
  destinationNode?: MediaStreamAudioDestinationNode;
}

interface ActiveSource {
  node: AudioBufferSourceNode;
  gainNode: GainNode;
  type: 'speech' | 'sfx' | 'music';
  id: string;
}

function resolveAudioUrl(url: string): string {
  if (!url) return url;
  if (
    url.startsWith('http://') ||
    url.startsWith('https://') ||
    url.startsWith('data:') ||
    url.startsWith('blob:')
  ) {
    return url;
  }
  // Media files generated by Edge-TTS or backend exports are served on backend
  if (url.startsWith('/media')) {
    const base = config.apiBase.replace(/\/+$/, '');
    return `${base}${url}`;
  }
  return url;
}

export class AudioEngine {
  private ctx: AudioContext | null = null;
  private masterGain: GainNode | null = null;
  private localGain: GainNode | null = null;
  private musicGain: GainNode | null = null;
  private speechGain: GainNode | null = null;
  private sfxGain: GainNode | null = null;
  private recordingDestination: MediaStreamAudioDestinationNode | null = null;

  private bufferCache = new Map<string, AudioBuffer>();
  private activeSources: ActiveSource[] = [];
  private activeSpeechTimers: number[] = [];
  private isMuted = false;
  private isLocalMuted = false;
  private isLoaded = false;
  private loadPromise: Promise<void> | null = null;

  constructor(opts?: { destinationNode?: MediaStreamAudioDestinationNode }) {
    if (opts?.destinationNode) {
      this.recordingDestination = opts.destinationNode;
    }
  }

  public initContext(): AudioContext {
    if (!this.ctx) {
      const AudioCtx =
        window.AudioContext ||
        (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      this.ctx = new AudioCtx();
      this.masterGain = this.ctx.createGain();
      this.localGain = this.ctx.createGain();
      this.musicGain = this.ctx.createGain();
      this.speechGain = this.ctx.createGain();
      this.sfxGain = this.ctx.createGain();

      this.speechGain.connect(this.masterGain);
      this.sfxGain.connect(this.masterGain);
      this.musicGain.connect(this.masterGain);

      // Connect local speakers via localGain (can be muted independently during export)
      this.masterGain.connect(this.localGain);
      this.localGain.connect(this.ctx.destination);

      // Connect recording destination directly to masterGain (always gets audio during export)
      if (this.recordingDestination) {
        this.masterGain.connect(this.recordingDestination);
      }
    }
    if (this.ctx.state === 'suspended') {
      this.ctx.resume().catch(() => {});
    }
    return this.ctx;
  }

  public async ensureContextResumed(): Promise<AudioContext> {
    const ctx = this.initContext();
    if (ctx.state === 'suspended') {
      try {
        await ctx.resume();
      } catch (err) {
        console.warn('[AudioEngine] ctx.resume() error:', err);
      }
    }
    return ctx;
  }

  public getContext(): AudioContext | null {
    return this.ctx;
  }

  public getMasterGain(): GainNode | null {
    return this.masterGain;
  }

  public setRecordingDestination(dest: MediaStreamAudioDestinationNode): void {
    this.recordingDestination = dest;
    if (this.masterGain) {
      try {
        this.masterGain.connect(dest);
      } catch {
        // ignore already connected
      }
    }
  }

  public setMuted(muted: boolean): void {
    this.isMuted = muted;
    if (this.localGain && this.ctx) {
      this.localGain.gain.setValueAtTime(muted ? 0 : 1, this.ctx.currentTime);
    }
  }

  public setLocalMuted(muted: boolean): void {
    this.isLocalMuted = muted;
    if (this.localGain && this.ctx) {
      this.localGain.gain.setValueAtTime(muted ? 0 : 1, this.ctx.currentTime);
    }
  }

  public getBuffer(url?: string, id?: string): AudioBuffer | undefined {
    if (url) {
      const b1 = this.bufferCache.get(url);
      if (b1) return b1;
      const b2 = this.bufferCache.get(resolveAudioUrl(url));
      if (b2) return b2;
    }
    if (id) {
      const b3 = this.bufferCache.get(id);
      if (b3) return b3;
    }
    return undefined;
  }

  /**
   * Preloads and decodes all audio files from manifest with concurrency cap 4.
   */
  public async loadManifest(
    manifest: AudioManifest | null,
    onProgress?: (p: number) => void
  ): Promise<void> {
    if (!manifest) {
      this.isLoaded = true;
      return;
    }

    const items: Array<{ id: string; url: string; isSpeech: boolean }> = [];

    if (manifest.lines) {
      for (const line of manifest.lines) {
        if (line.url) items.push({ id: line.line_id, url: line.url, isSpeech: true });
      }
    }
    if (manifest.music) {
      for (const m of manifest.music) {
        if (m.url) items.push({ id: m.music_id, url: m.url, isSpeech: false });
      }
    }
    if (manifest.sfx) {
      for (const s of manifest.sfx) {
        if (s.url) items.push({ id: s.sfx_id, url: s.url, isSpeech: false });
      }
    }

    const total = items.length;
    if (total === 0) {
      this.isLoaded = true;
      return;
    }

    const ctx = this.initContext();
    let completed = 0;
    const concurrency = 4;
    let index = 0;

    const worker = async () => {
      while (index < items.length) {
        const item = items[index++];
        if (this.getBuffer(item.url, item.id)) {
          completed++;
          onProgress?.(completed / total);
          continue;
        }

        try {
          const directUrl = resolveAudioUrl(item.url);
          let res = await fetch(directUrl);

          const contentType = res.headers.get('content-type') || '';
          const isHtml = contentType.includes('text/html');

          // Fallback to direct backend if dev server returned SPA html or 404
          if (!res.ok || isHtml) {
            const base = config.apiBase.replace(/\/+$/, '');
            if (!directUrl.startsWith(base) && item.url.startsWith('/')) {
              const fallbackUrl = `${base}${item.url}`;
              const fallbackRes = await fetch(fallbackUrl);
              const fallbackType = fallbackRes.headers.get('content-type') || '';
              if (fallbackRes.ok && !fallbackType.includes('text/html')) {
                res = fallbackRes;
              }
            }
          }

          if (!res.ok) throw new Error(`HTTP ${res.status}`);
          const finalType = res.headers.get('content-type') || '';
          if (finalType.includes('text/html')) {
            throw new Error(`Received HTML instead of audio buffer for ${item.url}`);
          }

          const arrayBuffer = await res.arrayBuffer();
          const audioBuffer = await ctx.decodeAudioData(arrayBuffer);

          this.bufferCache.set(item.url, audioBuffer);
          this.bufferCache.set(directUrl, audioBuffer);
          if (item.id) {
            this.bufferCache.set(item.id, audioBuffer);
          }

          if (item.isSpeech) {
            computeMouthTrack(item.id, audioBuffer);
          }
        } catch (err) {
          console.warn(`[AudioEngine] Failed to decode audio: ${item.url}`, err);
        } finally {
          completed++;
          onProgress?.(completed / total);
        }
      }
    };

    const workers = Array.from({ length: Math.min(concurrency, total) }, () => worker());
    await Promise.all(workers);
    this.isLoaded = true;
  }

  /**
   * Reschedules audio playback from a given time t along the timeline.
   */
  public syncPlayback(timeline: ResolvedTimeline, t: number, isPlaying: boolean): void {
    this.stopAll();

    if (!isPlaying || !this.ctx) return;

    if (this.ctx.state === 'suspended') {
      this.ctx
        .resume()
        .then(() => {
          if (isPlaying && this.ctx && this.ctx.state === 'running') {
            this.internalSchedule(timeline, t);
          }
        })
        .catch(() => {});
    }

    this.internalSchedule(timeline, t);
  }

  private internalSchedule(timeline: ResolvedTimeline, t: number): void {
    if (!this.ctx || this.ctx.state !== 'running') return;

    // Clear previous sources before scheduling
    this.stopAll();

    const now = this.ctx.currentTime;

    // Check if speech is currently active for music ducking
    const isSpeechActiveAtT = timeline.beats.some(
      (b) => b.speech && t >= b.startTime && t < b.endTime
    );

    // 1. Music scheduling (active or upcoming)
    const musicEvents = timeline.audioEvents.filter((e) => e.type === 'music');
    for (const ev of musicEvents) {
      const buf = this.getBuffer(ev.url, ev.id);
      if (!buf) continue;

      const musicStart = ev.startTime;
      const musicEnd = ev.duration ? musicStart + ev.duration : timeline.totalDuration;

      if (t >= musicStart && t < musicEnd) {
        const offset = (t - musicStart) % buf.duration;
        const source = this.ctx.createBufferSource();
        source.buffer = buf;
        source.loop = true;

        const gainNode = this.ctx.createGain();
        const baseVolume = ev.volume ?? 0.3;
        const duckedVolume = baseVolume * 0.25; // -12dB ducking
        gainNode.gain.setValueAtTime(isSpeechActiveAtT ? duckedVolume : baseVolume, now);

        source.connect(gainNode);
        if (this.musicGain) gainNode.connect(this.musicGain);

        source.start(now, offset);
        this.activeSources.push({ node: source, gainNode, type: 'music', id: ev.id });
      } else if (musicStart > t && musicStart < timeline.totalDuration) {
        const delay = musicStart - t;
        const source = this.ctx.createBufferSource();
        source.buffer = buf;
        source.loop = true;

        const gainNode = this.ctx.createGain();
        const baseVolume = ev.volume ?? 0.3;
        gainNode.gain.setValueAtTime(baseVolume, now + delay);

        source.connect(gainNode);
        if (this.musicGain) gainNode.connect(this.musicGain);

        source.start(now + delay, 0);
        this.activeSources.push({ node: source, gainNode, type: 'music', id: ev.id });
      }
    }

    // 2. Speech scheduling (active line with offset, or upcoming lines along timeline)
    for (const beat of timeline.beats) {
      if (!beat.speech) continue;
      const audioEv = beat.lineId ? timeline.audioEvents.find((e) => e.id === beat.lineId) : undefined;
      const url = audioEv?.url;
      const buf = this.getBuffer(url, beat.lineId);

      if (!buf) {
        // Fallback live speech synthesis if buffer is missing
        if (typeof window !== 'undefined' && 'speechSynthesis' in window && beat.speech.text) {
          this.scheduleSpeechSynthesis(beat.speech.text, beat.startTime, t);
        }
        continue;
      }

      if (t >= beat.startTime && t < beat.endTime) {
        const offset = t - beat.startTime;
        if (offset < buf.duration) {
          const source = this.ctx.createBufferSource();
          source.buffer = buf;

          const gainNode = this.ctx.createGain();
          gainNode.gain.setValueAtTime(1.0, now);

          source.connect(gainNode);
          if (this.speechGain) gainNode.connect(this.speechGain);

          source.start(now, offset);
          this.activeSources.push({
            node: source,
            gainNode,
            type: 'speech',
            id: beat.lineId || beat.beatId,
          });
        }
      } else if (beat.startTime > t) {
        const delay = beat.startTime - t;
        const source = this.ctx.createBufferSource();
        source.buffer = buf;

        const gainNode = this.ctx.createGain();
        gainNode.gain.setValueAtTime(1.0, now + delay);

        source.connect(gainNode);
        if (this.speechGain) gainNode.connect(this.speechGain);

        source.start(now + delay, 0);
        this.activeSources.push({
          node: source,
          gainNode,
          type: 'speech',
          id: beat.lineId || beat.beatId,
        });
      }
    }

    // 3. SFX scheduling (active or upcoming)
    const sfxEvents = timeline.audioEvents.filter((e) => e.type === 'sfx');
    for (const ev of sfxEvents) {
      const buf = this.getBuffer(ev.url, ev.id);
      if (!buf) continue;

      if (ev.startTime >= t) {
        const delay = ev.startTime - t;
        const source = this.ctx.createBufferSource();
        source.buffer = buf;

        const gainNode = this.ctx.createGain();
        gainNode.gain.setValueAtTime(ev.volume ?? 0.8, now + delay);

        source.connect(gainNode);
        if (this.sfxGain) gainNode.connect(this.sfxGain);

        source.start(now + delay, 0);
        this.activeSources.push({ node: source, gainNode, type: 'sfx', id: ev.id });
      } else if (t >= ev.startTime && t <= ev.startTime + 0.1) {
        const offset = t - ev.startTime;
        const source = this.ctx.createBufferSource();
        source.buffer = buf;

        const gainNode = this.ctx.createGain();
        gainNode.gain.setValueAtTime(ev.volume ?? 0.8, now);

        source.connect(gainNode);
        if (this.sfxGain) gainNode.connect(this.sfxGain);

        source.start(now, offset);
        this.activeSources.push({ node: source, gainNode, type: 'sfx', id: ev.id });
      }
    }
  }

  private scheduleSpeechSynthesis(text: string, startTime: number, currentTime: number): void {
    if (typeof window === 'undefined' || !('speechSynthesis' in window)) return;
    const delayMs = Math.max(0, (startTime - currentTime) * 1000);
    const timer = window.setTimeout(() => {
      try {
        const utterance = new SpeechSynthesisUtterance(text);
        utterance.rate = 1.0;
        window.speechSynthesis.speak(utterance);
      } catch (err) {
        console.warn('[AudioEngine] SpeechSynthesis error:', err);
      }
    }, delayMs);
    this.activeSpeechTimers.push(timer);
  }

  public stopAll(): void {
    for (const s of this.activeSources) {
      try {
        s.node.stop();
        s.node.disconnect();
        s.gainNode.disconnect();
      } catch {
        // already stopped
      }
    }
    this.activeSources = [];

    for (const timer of this.activeSpeechTimers) {
      clearTimeout(timer);
    }
    this.activeSpeechTimers = [];

    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.cancel();
    }
  }

  public pause(): void {
    if (this.ctx && this.ctx.state === 'running') {
      this.ctx.suspend().catch(() => {});
    }
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.pause();
    }
  }

  public resume(): void {
    if (this.ctx && this.ctx.state === 'suspended') {
      this.ctx.resume().catch(() => {});
    }
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.resume();
    }
  }

  public dispose(): void {
    this.stopAll();
    if (this.ctx) {
      this.ctx.close().catch(() => {});
      this.ctx = null;
    }
  }
}
